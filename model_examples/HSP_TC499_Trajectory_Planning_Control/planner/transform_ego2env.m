function [x_env, y_env] = transform_ego2env(x_ego, y_ego, car_x, car_y, yaw, pitch, roll)
% Transform the relative ego coordinates into the absolute environment
% coordinates.

wp_ego = [x_ego(:), y_ego(:)];
n_points = size(wp_ego, 1);
car = [car_x, car_y];

% initialize outputs
x_env = zeros(n_points,1);
y_env = zeros(n_points,1);

%% rotation matrices from ego perspective
rot_veh_yaw = [cos(yaw) -sin(yaw); sin(yaw) cos(yaw)];
rot_veh_pitch = [1 0; 0 cos(pitch)];
rot_veh_roll = [cos(roll) 0; 0 1];

%% inverse rotation
rot_road = rot_veh_yaw' * rot_veh_pitch' * rot_veh_roll';

%% apply the transformation
wp_env = zeros(n_points, 2);
wp_env = wp_ego * rot_road + repmat(car, [n_points, 1]);

x_env = wp_env(:,1);
y_env = wp_env(:,2);
