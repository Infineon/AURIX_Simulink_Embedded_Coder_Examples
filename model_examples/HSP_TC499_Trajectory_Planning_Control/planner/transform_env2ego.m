function [x_ego, y_ego] = transform_env2ego(x_env, y_env, car_x, car_y, yaw, pitch, roll)
% Transform the absolute enviroment coordinates into the relative ego
% coordinates.

wp_env = [x_env(:), y_env(:)];
n_points = size(wp_env, 1);
car = [car_x, car_y];

% initialize outputs
x_ego = zeros(n_points,1);
y_ego = zeros(n_points,1);

%% rotation matrices from ego perspective
rot_veh_yaw = [cos(yaw) -sin(yaw); sin(yaw) cos(yaw)];
rot_veh_pitch = [1 0; 0 cos(pitch)];
rot_veh_roll = [cos(roll) 0; 0 1];

rot_ego = rot_veh_yaw * rot_veh_pitch * rot_veh_roll;

%% apply the transformation
wp_ego = zeros(n_points, 2);
wp_ego = (wp_env - repmat(car, [n_points, 1])) * rot_ego;

x_ego(:) = wp_ego(:,1);
y_ego(:) = wp_ego(:,2);
