function [tgt_pos_x, tgt_pos_y, tgt_angle, tgt_curv, tgt_time, tgt_velo, tgt_accel] = ...
    extrapolate_trajectory(pos_x, pos_y, angle, curv, time, velo, accel)

    default_time = 0:49;

    path_velo = cumtrapz(time,velo);
    path_pos = cumsum([0; sqrt(diff(pos_x).^2 + diff(pos_y).^2)]);
    idx_path_pos = [diff(path_pos)>0; true];
    if path_pos(end) >= path_velo(end)
        % velo profile defines trajectory length
        % interpole to new time base

        seq_len = 30; %size(state_sequence, 1);
        Ts = 0.1;
        time = single(linspace(0,(seq_len-1)*Ts,seq_len));

        time_start = time(1);
        time_end = min(time(end),time(1)+5);
        tgt_time = (time_end-time_start)/49*default_time' + time_start;
        tgt_velo = interp1(time,velo,tgt_time,'linear','extrap');

        tgt_accel = interp1(time,accel,tgt_time,'linear','extrap');
        tgt_path = interp1(time,path_velo,tgt_time,'linear','extrap');
        if sum(idx_path_pos) <= 1
            tgt_pos_x = ones(50,1)*pos_x(idx_path_pos);
            tgt_pos_y = ones(50,1)*pos_y(idx_path_pos);
            tgt_angle = ones(50,1)*angle(idx_path_pos);
            tgt_curv = ones(50,1)*curv(idx_path_pos);
        else
            tgt_pos_x = interp1(path_pos(idx_path_pos),pos_x(idx_path_pos),tgt_path,'linear','extrap');
            tgt_pos_y = interp1(path_pos(idx_path_pos),pos_y(idx_path_pos),tgt_path,'linear','extrap');
            tgt_angle = interp1(path_pos(idx_path_pos),angle(idx_path_pos),tgt_path,'linear','extrap');
            tgt_curv = interp1(path_pos(idx_path_pos),curv(idx_path_pos),tgt_path,'linear','extrap');
        end
    else
        % position profile defines trajectory length
        % only take the valid segment of velo path
        path_valid_flag = [diff(path_velo) > 0; true];
        time_pos_valid = interp1(path_velo(path_valid_flag),time(path_valid_flag),path_pos(path_valid_flag),'linear','extrap');
        time_pos_valid_flag = [diff(time_pos_valid) > 0; true];
        time_pos_valid = time_pos_valid(time_pos_valid_flag);
        path_valid_flag(path_valid_flag) = time_pos_valid_flag;
        time_start = time_pos_valid(1);
        time_end = time(end);
        tgt_time = (time_end-time_start)/49*default_time' + time_start; %
        tgt_velo = interp1(time,velo,tgt_time,'linear','extrap');
        tgt_accel = interp1(time,accel,tgt_time,'linear','extrap');
        if sum(idx_path_pos) <= 1 % 
            tgt_pos_x = ones(50,1)*pos_x(idx_path_pos);
            tgt_pos_y = ones(50,1)*pos_y(idx_path_pos);
            tgt_angle = ones(50,1)*angle(idx_path_pos);
            tgt_curv = ones(50,1)*curv(idx_path_pos);
        else
            tgt_pos_x = interp1(time_pos_valid,pos_x(path_valid_flag),tgt_time,'linear','extrap');
            tgt_pos_y = interp1(time_pos_valid,pos_y(path_valid_flag),tgt_time,'linear','extrap');
            tgt_angle = interp1(time_pos_valid,angle(path_valid_flag),tgt_time,'linear','extrap');
            tgt_curv = interp1(time_pos_valid,curv(path_valid_flag),tgt_time,'linear','extrap');
        end
    end
