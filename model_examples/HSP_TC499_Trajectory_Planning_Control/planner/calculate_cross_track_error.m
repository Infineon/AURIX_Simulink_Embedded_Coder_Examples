function cte = calculate_cross_track_error(traj_x, traj_y, ego_x, ego_y, ego_yaw)
    min_distance = single(inf);
    closest_point = single([0, 0]);
    
    for i = 1:5 % numel(traj_x) - 1
        x_start = traj_x(i);
        y_start = traj_y(i);
        x_end = traj_x(i+1);
        y_end = traj_y(i+1);
        
        % Line segment vector
        segment_vec = [x_end - x_start, y_end - y_start];
        segment_length = norm(segment_vec);
        segment_unit_vec = segment_vec / segment_length;
        
        % Vector from start of segment to reference point
        point_vec = [ego_x - x_start, ego_y - y_start];
        
        % Project point_vec onto segment_vec to find the closest point on the segment
        projection_length = dot(point_vec, segment_unit_vec);
        
        closest_point_on_segment = [x_start, y_start] + projection_length * segment_unit_vec;
        distance_to_segment = norm(closest_point_on_segment - [ego_x, ego_y]);
        
        if distance_to_segment < min_distance
            min_distance = distance_to_segment;
            closest_point = closest_point_on_segment;
        end
    end

    % Calculate the cross-track error
    cte = min_distance;
    
    % Determine the sign of the cross-track error using heading orientation
    trajectory_vec = closest_point - [ego_x, ego_y];
    heading_vec = [cos(ego_yaw), sin(ego_yaw)];
    
    cross_product = trajectory_vec(1) * heading_vec(2) - trajectory_vec(2) * heading_vec(1);
    
    if cross_product > 0
        % positive left of the ref., negative right of the ref.
        % following the CM convention
        cte = -cte;
    end
end
