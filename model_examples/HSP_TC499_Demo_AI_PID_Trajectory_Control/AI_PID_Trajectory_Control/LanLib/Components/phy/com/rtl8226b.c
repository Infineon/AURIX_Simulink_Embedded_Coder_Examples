        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xB82E, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= (~BIT_0);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xB82E, phydata);
        if (error != FALSE)
            goto exit;

