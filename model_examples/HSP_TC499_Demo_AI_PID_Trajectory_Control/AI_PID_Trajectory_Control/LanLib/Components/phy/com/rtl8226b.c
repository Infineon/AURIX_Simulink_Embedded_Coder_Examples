boolean Rtl8226b_eeeEnable_get(IfxGeth_PhyHandle *const handle, PHY_EEE_ENABLE *pEeeEnable)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 60, &phydata);
    if (error != FALSE)
        goto exit;

    pEeeEnable->EEE_100 = (phydata & BIT_1) ? (FALSE) : (TRUE);
    pEeeEnable->EEE_1000 = (phydata & BIT_2) ? (FALSE) : (TRUE);

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 62, &phydata);
    if (error != FALSE)
        goto exit;

    pEeeEnable->EEE_2_5G = (phydata & BIT_0) ? (FALSE) : (TRUE);

exit:
    return error;
}

boolean Rtl8226b_eeeEnable_set(IfxGeth_PhyHandle *const handle, PHY_EEE_ENABLE *pEeeEnable)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    boolean AnEnable = 0;

    error = Rtl8226b_autoNegoEnable_get(handle, &AnEnable);
    if (error != FALSE)
        goto exit;

    // 100M/1G EEE
    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 60, &phydata);
    if (error != FALSE)
        goto exit;

    if (pEeeEnable->EEE_100)
        phydata |= BIT_1;
    else
        phydata &= (~BIT_1);

    if (pEeeEnable->EEE_1000)
        phydata |= BIT_2;
    else
        phydata &= (~BIT_2);

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 60, phydata);
    if (error != FALSE)
        goto exit;

    // 2.5G EEE
    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 62, &phydata);
    if (error != FALSE)
        goto exit;

    if (pEeeEnable->EEE_2_5G)
        phydata |= BIT_0;
    else
        phydata &= (~BIT_0);

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 62, phydata);
    if (error != FALSE)
        goto exit;

    // RestartAutoNegotiation
    if (AnEnable)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA400, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= BIT_9;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, phydata);
    }

exit:
    return error;
}





