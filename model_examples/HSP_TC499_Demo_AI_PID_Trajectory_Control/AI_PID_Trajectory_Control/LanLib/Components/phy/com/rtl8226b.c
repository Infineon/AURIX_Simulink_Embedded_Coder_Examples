boolean Rtl8226b_crossOverMode_get(IfxGeth_PhyHandle *const handle, PHY_CROSSPVER_MODE *CrossOverMode)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA430, &phydata);
    if (error != FALSE)
        goto exit;

    if ((phydata & BIT_9) >> 9)
    {
        switch ((phydata & BIT_8) >> 8)
        {
            case 1:
                *CrossOverMode = PHY_CROSSPVER_MODE_MDI;
                break;
            case 0:
                *CrossOverMode = PHY_CROSSPVER_MODE_MDIX;
                break;
            default:
                error = TRUE;
                break;
        }
    }
    else
    {
        *CrossOverMode = PHY_CROSSPVER_MODE_AUTO;
    }

exit:
    return error;
}

boolean Rtl8226b_crossOverMode_set(IfxGeth_PhyHandle *const handle, PHY_CROSSPVER_MODE CrossOverMode)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA430, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~(BIT_8 | BIT_9));

    switch(CrossOverMode)
    {
        case PHY_CROSSPVER_MODE_MDI:
            phydata |= (BIT_8 | BIT_9);
            break;
        case PHY_CROSSPVER_MODE_MDIX:
            phydata |= BIT_9;
            break;
        case PHY_CROSSPVER_MODE_AUTO:
            break;
        default:
            error = TRUE;
            goto exit;
    }

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA430, phydata);
    if (error != FALSE)
        goto exit;

    if (CrossOverMode != PHY_CROSSPVER_MODE_AUTO)
    {
        // RestartAutoNegotiation
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA400, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= BIT_9;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, phydata);
    }

exit:
    return error;
}

