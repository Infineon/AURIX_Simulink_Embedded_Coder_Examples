boolean Rtl8226b_rtct_start(IfxGeth_PhyHandle *const handle)
{
    boolean error = TRUE;
    uint16 phydata = 0;
    IfxGeth_PhyLinkState linkOK = IfxGeth_PhyLinkState_Down;
    uint16 Speed;

    error = Rtl8226b_is_link(handle, &linkOK);
    if (error != FALSE)
        goto exit;

    if (linkOK == IfxGeth_PhyLinkState_Up)
    {
        error = Rtl8226b_speed_get(handle, &Speed);
        if (error != FALSE)
            goto exit;

        //RTCT is not supported when port link at 10M.
        if (Speed == 10)
        {
            /* printf("RTCT is not supported when port link at 10M.\n\r"); */
            error = TRUE;
            goto exit;
        }
    }
    else
    {
        // MMD 31.0xA422[15] = 0    // clear rtct_done
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= (~BIT_15);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
        if (error != FALSE)
            goto exit;

        // wait 1ms for chip reset the states
        Sleep(1);

        // MMD 31.0xA422[4] = 1    // RTCT_CH_A
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= (BIT_4);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
        if (error != FALSE)
            goto exit;

        // MMD 31.0xA422[5] = 1    // RTCT_CH_B
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= (BIT_5);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
        if (error != FALSE)
            goto exit;

        // MMD 31.0xA422[6] = 1    // RTCT_CH_C
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= (BIT_6);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
        if (error != FALSE)
            goto exit;

        // MMD 31.0xA422[7] = 1    // RTCT_CH_D
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= (BIT_7);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
        if (error != FALSE)
            goto exit;

        // MMD 31.0xA422[0] = 1    // RTCT_ENABLE
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= (BIT_0);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA422, phydata);
    }

exit:
    return error;
}

boolean Rtl8226b_rtctResult_convert(uint16 phydata, PHY_RTCT_STATUS *pRtctStatus)
{
    boolean error = FALSE;

    switch (phydata)
    {
        case 0x60: // Normal
            break;
        case 0x48:
            pRtctStatus->Open = TRUE;
            break;
        case 0x50:
            pRtctStatus->Short = TRUE;
            break;
        case 0x42:
            pRtctStatus->Mismatch = MIS_MATCH_OPEN;
            break;
        case 0x44:
            pRtctStatus->Mismatch = MIS_MATCH_SHORT;
            break;
        default:
            error = TRUE;
            break;
    }

    return error;
}

boolean Rtl8226b_rtctResult_get(IfxGeth_PhyHandle *const handle, PHY_RTCT_RESULT *pRtctResult)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    IfxGeth_PhyLinkState linkOK = IfxGeth_PhyLinkState_Down;

    uint16 Speed = NO_LINK;

    boolean rtct_done;

    error = Rtl8226b_is_link(handle, &linkOK);
    if (error != FALSE)
        goto exit;

    if (linkOK == IfxGeth_PhyLinkState_Up)
    {
        error = Rtl8226b_speed_get(handle, &Speed);
        if (error != FALSE)
            goto exit;

        pRtctResult->linkType = Speed;
        if (Speed == 10)
        {
            /* printf("RTCT is not supported when port link at 10M.\n\r"); */
            error = TRUE;
            goto exit;
        }

        switch(Speed)
        {
            case LINK_SPEED_100M:
                // rxLen = MMD 31.0xA880[7:0] * 100    // unit is meter
                // txLen = MMD 31.0xA880[7:0] * 100
                error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA880, &phydata);
                if (error != FALSE)
                    goto exit;

                pRtctResult->rxLen = (phydata & 0xff) * 100;
                pRtctResult->txLen = (phydata & 0xff) * 100;
                break;

            case LINK_SPEED_1G:
                // channelALen = MMD 31.0xA880[7:0] * 100    // unit is meter
                // channelBLen = MMD 31.0xA880[7:0] * 100
                // channelCLen = MMD 31.0xA880[7:0] * 100
                // channelDLen = MMD 31.0xA880[7:0] * 100
                error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA880, &phydata);
                if (error != FALSE)
                    goto exit;

                pRtctResult->channelALen = (phydata & 0xff) * 100;
                pRtctResult->channelBLen = (phydata & 0xff) * 100;
                pRtctResult->channelCLen = (phydata & 0xff) * 100;
                pRtctResult->channelDLen = (phydata & 0xff) * 100;
                break;

            case LINK_SPEED_2P5G:
                //channelALen = MMD 31.0xACBA[9:2] * 100        // cablen for XG
                error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xACBA, &phydata);
                if (error != FALSE)
                    goto exit;

                pRtctResult->channelALen = ((phydata & 0x3fc) >> 2 ) * 100;
                pRtctResult->channelBLen = ((phydata & 0x3fc) >> 2 ) * 100;
                pRtctResult->channelCLen = ((phydata & 0x3fc) >> 2 ) * 100;
                pRtctResult->channelDLen = ((phydata & 0x3fc) >> 2 ) * 100;
                break;

            //RTCT is not supported when port link at 10M.
            default:
                error = TRUE;
                break;
        }
    }
    else
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA422, &phydata);
        if (error != FALSE)
            goto exit;

        rtct_done = (phydata & BIT_15) ? (TRUE) : (FALSE);

        if (!rtct_done)
        {
            error = TRUE;
            goto exit;
        }

        // MMD 31.0A436[15:0] = 0x8029
        // phyData = read MMD 31.0A438[15:0]
        // channelALen = phyData * 100 / 80
        // channelALen (unit: cm)
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x8029);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        pRtctResult->channelALen = (phydata * 100) / 80;

        // MMD 31.0A436[15:0] = 0x802D
        // phyData = read MMD 31.0A438[15:0]
        // channelBLen = phyData * 100 / 80
        // channelBLen (unit: cm)
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x802D);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        pRtctResult->channelBLen = (phydata * 100) / 80;

        // MMD 31.0A436[15:0] = 0x8031
        // phyData = read MMD 31.0A438[15:0]
        // channelCLen = phyData * 100 / 80
        // channelCLen (unit: cm)
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x8031);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        pRtctResult->channelCLen = (phydata * 100) / 80;

        // MMD 31.0A436[15:0] = 0x8035
        // phyData = read MMD 31.0A438[15:0]
        // channelDLen = phyData * 100 / 80
        // channelDLen (unit: cm)
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x8035);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        pRtctResult->channelDLen = (phydata * 100) / 80;

        // channelA error
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x8027);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        error = Rtl8226b_rtctResult_convert(phydata, &pRtctResult->channelAStatus);
        if (error != FALSE)
            goto exit;

        // channelA error
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x802B);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        error = Rtl8226b_rtctResult_convert(phydata, &pRtctResult->channelBStatus);
        if (error != FALSE)
            goto exit;

        // channelC error
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x802F);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        error = Rtl8226b_rtctResult_convert(phydata, &pRtctResult->channelCStatus);
        if (error != FALSE)
            goto exit;

        // channelD error
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA436, 0x8033);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0x0A438, &phydata);
        if (error != FALSE)
            goto exit;

        error = Rtl8226b_rtctResult_convert(phydata, &pRtctResult->channelDStatus);
    }

exit:
    return error;
}




