boolean Rtl8226b_is_link(IfxGeth_PhyHandle *const handle, IfxGeth_PhyLinkState *plinkOK)
{
    boolean error = FALSE;
    uint16 phydata = 0;

    uint8 i = 0;

    // must read twice
    for(i = 0; i < 2; i++)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA402, &phydata);
        if (error != FALSE)
            goto exit;
    }

    *plinkOK = (phydata & BIT_2) ? (IfxGeth_PhyLinkState_Up) : (IfxGeth_PhyLinkState_Down);

exit:
    return error;
}

boolean Rtl8226b_speed_get(IfxGeth_PhyHandle *const handle, uint16 *pSpeed)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    uint8 speed_grp = 0;
    uint8 speed = NO_LINK;

    IfxGeth_PhyLinkState linkOK = IfxGeth_PhyLinkState_Down;

    error = Rtl8226b_is_link(handle, &linkOK);
    if (error != FALSE)
        goto exit;

    if (linkOK == IfxGeth_PhyLinkState_Up)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA434, &phydata);
        if (error != FALSE)
            goto exit;

        speed_grp = (phydata & (BIT_9 | BIT_10)) >> 9;
        speed = (phydata & (BIT_4 | BIT_5)) >> 4;

        switch(speed_grp)
        {
            case 0:
            {
                switch(speed)
                {
                    case 0:
                        *pSpeed = LINK_SPEED_10M;
                        break;
                    case 1:
                        *pSpeed = LINK_SPEED_100M;
                        break;
                    case 2:
                        *pSpeed = LINK_SPEED_1G;
                        break;
                    case 3:
                        *pSpeed = LINK_SPEED_500M;
                        break;

                    default:
                        error = TRUE;
                        break;
                }
                break;
            }

            case 1:
            {
                switch(speed)
                {
                    case 1:
                        *pSpeed = LINK_SPEED_2P5G;
                        break;
                    case 3:
                        *pSpeed = LINK_SPEED_1G;        // 2.5G lite
                        break;
                    default:
                        error = TRUE;
                        break;
                }
                break;
            }

            default:
                error = TRUE;
                break;
        }
    }
    else
    {
        *pSpeed = NO_LINK;
    }

exit:
    return error;
}

