boolean Rtl8226b_wol_set(IfxGeth_PhyHandle *const handle, PHY_WOL_EVENT *pwolevent)
{
    boolean error = TRUE;
    IfxGeth_PhyLinkState linkOK;
    uint16 speed;
    uint16 phydata = 0, phydata2=0;

    error = Rtl8226b_is_link(handle, &linkOK);
    if (error != FALSE)
        goto exit;

    if (linkOK == IfxGeth_PhyLinkState_Up)
    {
        error = Rtl8226b_speed_get(handle, &speed);
        if (error != FALSE)
            goto exit;

        //WOL is not supported when port link at 2.5G.
        if (speed == LINK_SPEED_2P5G)
        {
            /* printf("WOL/PME is not supported when port link at 2.5G.\n\r"); */
            error = TRUE;
            goto exit;
        }
     }

    //Set INTB/PMEB pinas PMEB(optional) MMD31, reg 0xD05C, bit0=1
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xD05C, &phydata);
    if (error != FALSE)
        goto exit;

    phydata |= BIT_0;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD05C, phydata);
    if (error != FALSE)
        goto exit;

    // wait 1ms
    Sleep(1);

    //Set MAC address  MMD31, reg 0xD8C0,0xD8C2,0xD8C4
    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8C0, pwolevent->macaddress.ADDR15_0);

    if (error != FALSE)
        goto exit;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8C2, pwolevent->macaddress.ADDR31_16);
    if (error != FALSE)
        goto exit;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8C4, pwolevent->macaddress.ADDR47_32);
    if (error != FALSE)
        goto exit;

    //Set Max packet length MMD31, reg 0xD8A2
    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8A2,  (uint16)pwolevent->MAXPKTLENGTH);
    if (error != FALSE)
        goto exit;

    //WOL event select and enable  MMD31, reg 0xD8A0
    if(pwolevent->LINKCHG)
        phydata2 |= BIT_13;

    if(pwolevent->MAGIC)
        phydata2 |= BIT_12;

    if(pwolevent->ARBITRARY)
        phydata2 |= BIT_11;

    if(pwolevent->UNICAST)
        phydata2 |= BIT_10;

    if(pwolevent->MULTICAST)
        phydata2 |= BIT_9;

    if(pwolevent->BROADCAST)
        phydata2 |= BIT_8;

    if(pwolevent->FRAME7)
        phydata2 |= BIT_7;

    if(pwolevent->FRAME6)
        phydata2 |= BIT_6;

    if(pwolevent->FRAME5)
        phydata2 |= BIT_5;

    if(pwolevent->FRAME4)
        phydata2 |= BIT_4;

    if(pwolevent->FRAME3)
        phydata2 |= BIT_3;

    if(pwolevent->FRAME2)
        phydata2 |= BIT_2;

    if(pwolevent->FRAME1)
        phydata2 |= BIT_1;

    if(pwolevent->FRAME0)
        phydata2 |= BIT_0;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8A0,  phydata2);
    if (error != FALSE)
        goto exit;

    if (pwolevent->MULTICAST)
    {
        //Set Multicast register  MMD31, reg 0xD8C6,0xD8C8,0xD8CA,0xD8CC
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8C6, pwolevent->multicast.REG15_0);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8C8, pwolevent->multicast.REG31_16);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8CA, pwolevent->multicast.REG47_32);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8CC, pwolevent->multicast.REG63_48);
        if (error != FALSE)
            goto exit;
    }

    //Set Wakeup Frame #0
    if (pwolevent->FRAME0)
    {
        //Set Mask
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD800, pwolevent->wakeframe0.MASK15_0);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD802, pwolevent->wakeframe0.MASK31_16);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD804, pwolevent->wakeframe0.MASK47_32);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD806, pwolevent->wakeframe0.MASK63_48);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD808, pwolevent->wakeframe0.MASK79_64);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD80A, pwolevent->wakeframe0.MASK95_80);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD80C, pwolevent->wakeframe0.MASK111_96);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD80E, pwolevent->wakeframe0.MASK127_112);
        if (error != FALSE)
            goto exit;

        //Set CRC
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD880, pwolevent->wakeframe0.CRC);
    }

exit:
    return error;
}

boolean Rtl8226b_wol_exit(IfxGeth_PhyHandle *const handle)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    //Disable all WOL events
    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8A0,  0x0000);
    if (error != FALSE)
        goto exit;

    //WOL reset
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xD8A2, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~BIT_15);

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xD8A2, phydata);
    if (error != FALSE)
        goto exit;

exit:
    return error;
}
