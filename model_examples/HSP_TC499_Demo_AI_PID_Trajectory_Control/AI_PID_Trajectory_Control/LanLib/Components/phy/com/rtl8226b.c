boolean Rtl8226b_ieeeTestMode_set(IfxGeth_PhyHandle *const handle, uint16 Speed, PHY_IEEE_TEST_MODE *pIEEEtestmode)
{
    boolean error = TRUE;
    uint16 phydata = 0, phydata_w = 0, phydata2 = 0;

    switch (Speed)
    {
        case LINK_SPEED_10M:
        {
            //initial setting
            //Write MMD1, reg 0x0000, data=0x0000
            error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, 0x0000);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD7, reg 0x0000, bit[12]=0x0
            error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
            if (error != FALSE)
                goto exit;

            phydata &= (~BIT_12);

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD31, reg 0xA412, bit[15:13]=0x0
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA412, &phydata);
            if (error != FALSE)
                goto exit;

            phydata &= (~(BIT_15 | BIT_14 | BIT_13));

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, phydata);
            if (error != FALSE)
                 goto exit;

            // wait 1ms
            Sleep(1);

            if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_A)
                Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_MDI);
            else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_B)
                Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_MDIX);

            if(pIEEEtestmode -> NORMAL)
            {
              //Write MMD31, reg 0xC804, data=0x0115
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC804, 0x0115);
              if (error != FALSE)
                 goto exit;

              //Write MMD31, reg 0xC800, data=0x5a21
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC800, 0x5a21);
              if (error != FALSE)
                 goto exit;
            }

            if(pIEEEtestmode -> HARMONIC)
            {
              //Write MMD31, reg 0xC804, data=0x0015
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC804, 0x0015);
              if (error != FALSE)
                 goto exit;

              //Write MMD31, reg 0xC800, data=0xff21
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC800, 0xff21);
              if (error != FALSE)
                 goto exit;
            }

            if(pIEEEtestmode -> LINKPLUSE)
            {
              //Write MMD31, reg 0xC804, data=0x0115
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC804, 0x0115);
              if (error != FALSE)
                 goto exit;

              //Write MMD31, reg 0xC800, data=0x5a00
              error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC800, 0x5a00);
              if (error != FALSE)
                 goto exit;
            }

            if (pIEEEtestmode->TMFINISH)
            {
                //MMD31, reg 0xA430, bit[9:8]=0x0
                 Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_AUTO);

                // wait 1ms
                Sleep(1);

               //Write MMD31, reg 0xC804, data=0x0115
               error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC804, 0x0115);
               if (error != FALSE)
                  goto exit;

                // wait 1ms
                Sleep(1);

               //Write MMD31, reg 0xC800, data=0x5a00
               error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xC800, 0x5a00);
               if (error != FALSE)
                 goto exit;

                // wait 1ms
                Sleep(1);

                //Write MMD7, reg 0x0000, bit[12]=0x1
                error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata |= BIT_12;

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
                if (error != FALSE)
                    goto exit;

                // wait 1ms
                Sleep(1);

                //Write MMD1, reg 0x0000, bit[15]=0x1, PMA reset
                error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata |= BIT_15;

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, phydata);
                if (error != FALSE)
                      goto exit;
            }
        }
        break;

        case LINK_SPEED_100M:
        {
            //initial setting
            //Write MMD1, reg 0x0000, data=0x2000
            error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, 0x2000);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD7, reg 0x0000, bit[12]=0x0
            error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
            if (error != FALSE)
                goto exit;

            phydata &= (~BIT_12);

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
            if (error != FALSE)
                    goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD31, reg 0xA412, bit[15:13]=0x0
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA412, &phydata);
            if (error != FALSE)
                goto exit;

            phydata &= (~(BIT_15 | BIT_14 | BIT_13));

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, phydata);
            if (error != FALSE)
                 goto exit;

            // wait 1ms
            Sleep(1);

            if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_A)
                Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_MDI);
            else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_B)
                Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_MDIX);

            if (pIEEEtestmode->TMFINISH)
            {
                //MMD31, reg 0xA430, bit[9:8]=0x0
                 Rtl8226b_crossOverMode_set(handle,PHY_CROSSPVER_MODE_AUTO);

                // wait 1ms
                Sleep(1);

                //Write MMD7, reg 0x0000, bit[12]=0x1
                error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata |= BIT_12;

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
                if (error != FALSE)
                    goto exit;

                // wait 1ms
                Sleep(1);

                //Write MMD1, reg 0x0000, bit[15]=0x1, PMA reset
                error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata |= BIT_15;

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, phydata);
                if (error != FALSE)
                      goto exit;
            }
        }
        break;

        case LINK_SPEED_1G:
        {
            //initial setting
            //Write MMD1, reg 0x0000, bit[15]=0x1, PMA reset
            error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, &phydata);
            if (error != FALSE)
                goto exit;

             phydata |= BIT_15;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, phydata);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD7, reg 0x0000, bit[12]=0x1
            error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
            if (error != FALSE)
                goto exit;

            phydata |= BIT_12;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Config channel
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, &phydata);
            if (error != FALSE)
                goto exit;

            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD32, &phydata2);
            if (error != FALSE)
                goto exit;

            if (pIEEEtestmode -> channel == TESTMODE_CHANNEL_NONE)
            {
                phydata &= (~(BIT_10));
            }
            else
            {
                phydata |= BIT_10;

                if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_A)
                    phydata_w = 1 << 8;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_B)
                    phydata_w = 2 << 8;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_C)
                    phydata_w = 4 << 8;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_D)
                    phydata_w = 8 << 8;

                phydata2 &= (~(BIT_11 | BIT_10 | BIT_9 | BIT_8));
                phydata2 |= phydata_w;
            }

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD32, phydata2);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, phydata);
            if (error != FALSE)
                goto exit;

            //1G Test Mode
            if (pIEEEtestmode->TM1)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, 0x2000);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM2)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, 0x4000);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM4)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, 0x8000);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TMFINISH)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, 0x0000);
                if (error != FALSE)
                    goto exit;

                error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata &= (~(BIT_10));

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, phydata);
                if (error != FALSE)
                    goto exit;
            }
        }
        break;

        case LINK_SPEED_2P5G:
        {
            //initial setting
            //Write MMD7, reg 0x0000, bit[12]=0x1
            error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0x0000, &phydata);
            if (error != FALSE)
                goto exit;

            phydata |= BIT_12;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0x0000, phydata);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD31, reg 0xA412, bit[15:13]=0x0
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA412, &phydata);
            if (error != FALSE)
                goto exit;

            phydata &= (~(BIT_15 | BIT_14 | BIT_13));

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, phydata);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Write MMD1, reg 0x0000, data 0x2058
            error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0000, 0x2058);
            if (error != FALSE)
                goto exit;

            // wait 1ms
            Sleep(1);

            //Config channel
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, &phydata);
            if (error != FALSE)
                goto exit;

            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD32, &phydata2);
            if (error != FALSE)
                goto exit;

            if (pIEEEtestmode -> channel == TESTMODE_CHANNEL_NONE)
            {
                phydata &= (~(BIT_8));
            }
            else
            {
                phydata |= BIT_8;

                if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_A)
                    phydata_w = 1;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_B)
                    phydata_w = 2;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_C)
                    phydata_w = 4;
                else if(pIEEEtestmode -> channel == TESTMODE_CHANNEL_D)
                    phydata_w = 8;

                phydata2 &= (~(BIT_3 | BIT_2 | BIT_1 | BIT_0));
                phydata2 |= phydata_w;
            }

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD32, phydata2);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, phydata);
            if (error != FALSE)
                goto exit;

            // 2.5G Test Mode
            if (pIEEEtestmode->TM1)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x2400);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM2)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x4400);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM3)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x6400);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM4)
            {
                if (pIEEEtestmode->TONE1)
                {
                    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x8400);
                    if (error != FALSE)
                        goto exit;
                }

                if (pIEEEtestmode->TONE2)
                {
                    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x8800);
                    if (error != FALSE)
                        goto exit;
                }

                if (pIEEEtestmode->TONE3)
                {
                    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x9000);
                    if (error != FALSE)
                        goto exit;
                }

                if (pIEEEtestmode->TONE4)
                {
                    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x9400);
                    if (error != FALSE)
                        goto exit;
                }

                if (pIEEEtestmode->TONE5)
                {
                    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0x9800);
                    if (error != FALSE)
                        goto exit;
                }
            }

            if (pIEEEtestmode->TM5)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0xA400);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TM6)
            {
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 132, 0xC400);
                if (error != FALSE)
                    goto exit;
            }

            if (pIEEEtestmode->TMFINISH)
            {
                error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, &phydata);
                if (error != FALSE)
                    goto exit;

                phydata &= (~(BIT_8));

                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xBD2C, phydata);
                if (error != FALSE)
                    goto exit;

                //re-nway and set phy_rst)
                error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, 0x9200);
                if (error != FALSE)
                    goto exit;
            }
        }
        break;

        default:
            error = TRUE;
            break;
    }

exit:
    return error;
}

boolean Rtl8226b_serdes_rst(IfxGeth_PhyHandle *const handle)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x7581, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~BIT_4);

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x7581, phydata);
    if (error != FALSE)
        goto exit;

    // wait 1ms
    Sleep(1);

    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x7581, &phydata);
    if (error != FALSE)
        goto exit;

    phydata |= BIT_4;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x7581, phydata);
    if (error != FALSE)
        goto exit;

    // wait 1ms
    Sleep(1);

exit:
    return error;
}

boolean Rtl8226b_serdes_link_get(IfxGeth_PhyHandle *const handle, boolean *perdesLink, PHY_SERDES_MODE *SerdesMode)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    // serdes link
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x758D, &phydata);
    if (error != FALSE)
        goto exit;

    *perdesLink = (phydata & BIT_1) ? (TRUE) : (FALSE);

    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x758B, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= BIT_0;

    if (phydata == 1)
    {
        //serdes mode
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x7580, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= (BIT_4 | BIT_3 | BIT_2 | BIT_1 | BIT_0);

        if (phydata == 2)
            *SerdesMode = PHY_SERDES_MODE_SGMII;
        else if(phydata == 13)
            *SerdesMode = PHY_SERDES_MODE_USXGMII;
        else if(phydata == 18)
            *SerdesMode = PHY_SERDES_MODE_HiSGMII;
        else if(phydata == 22)
            *SerdesMode = PHY_SERDES_MODE_2500BASEX;
        else if(phydata == 31)
            *SerdesMode = PHY_SERDES_MODE_NO_SDS;
        else
            *SerdesMode = PHY_SERDES_MODE_OTHER;
    }
    else
    {
        *SerdesMode = PHY_SERDES_MODE_NO_SDS;
    }

exit:
    return error;
}

boolean Rtl8226b_serdes_option_set(IfxGeth_PhyHandle *const handle, uint8 functioninput)
{
    boolean error = TRUE, blinkOk = TRUE;
    uint16 phydata = 0, nTimeout = 100;

    if ((functioninput >= 0) && (functioninput <= 3))
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x75F3, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= ~BIT_0 ;
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x75F3, phydata);
        if (error != FALSE)
            goto exit;

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND1, 0x697A, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= (~(BIT_0 | BIT_1 | BIT_2 | BIT_3 | BIT_4 | BIT_5));
        phydata |= functioninput;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x697A, phydata);
        if (error != FALSE)
            goto exit;

        if ((functioninput == 0) || (functioninput == 2))
        {
            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6A04, 0x0503);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6F10, 0xD455);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6F11, 0x8020);
            if (error != FALSE)
                goto exit;
        }
        else if ((functioninput == 1) || (functioninput == 3))
        {
            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6A04, 0x0503);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6F10, 0xD433);
            if (error != FALSE)
                goto exit;

            error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND1, 0x6F11, 0x8020);
            if (error != FALSE)
                goto exit;
        }

        // change link state
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA400, &phydata);
        if (error != FALSE)
            goto exit;

        phydata |= BIT_14 ;
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, phydata);
        if (error != FALSE)
            goto exit;

        do
        {
            error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA434, &phydata);
            if (error != FALSE)
                goto exit;

            blinkOk = (phydata & BIT_2) ? (TRUE) : (FALSE);

            if (blinkOk) break;

            Sleep(100);

            nTimeout --;
            //osal_printf("blinkOk %x, nTimeout = %d\n",phydata,nTimeout);
        }
        while (nTimeout > 0);

        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA400, &phydata);
        if (error != FALSE)
            goto exit;

        phydata &= ~BIT_14 ;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, phydata);
    }

exit:
    return error;
}

