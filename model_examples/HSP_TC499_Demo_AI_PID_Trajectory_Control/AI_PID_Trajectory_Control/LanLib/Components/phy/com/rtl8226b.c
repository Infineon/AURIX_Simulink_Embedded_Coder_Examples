boolean Rtl8226b_phy_reset(IfxGeth_PhyHandle *const handle)
{
    boolean error = TRUE;
    uint16 phydata0 = 0, phydata1 = 0;
    uint16 waitcount = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0x0, &phydata0);
    if (error != FALSE)
        goto exit;

    phydata1 |= BIT_15;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0, phydata1);
    if (error != FALSE)
        goto exit;

    for(;;)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0x0, &phydata1);
        if (error != FALSE)
            goto exit;

        if (!(phydata1 & BIT_15))
            break;

        if (++waitcount == 500)
        {
            error = TRUE;
            goto exit;
        }
    }

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0x0, phydata0);
    if (error != FALSE)
        goto exit;

exit:
    return error;
}

boolean Rtl8226b_autoNegoEnable_get(IfxGeth_PhyHandle *const handle, boolean *pEnable)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0, &phydata);
    if (error != FALSE)
        goto exit;

    *pEnable = (phydata & BIT_12) ? (TRUE) : (FALSE);

exit:
    return error;
}

boolean Rtl8226b_autoNegoEnable_set(IfxGeth_PhyHandle *const handle, boolean Enable)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    // AutoNegotiationEnable
    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0, &phydata);
    if (error != FALSE)
        goto exit;

    if (Enable)
        phydata |= BIT_12;
    else
        phydata &= (~BIT_12);

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0, phydata);
    if (error != FALSE)
        goto exit;

    // RestartAutoNegotiation
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA400, &phydata);
    if (error != FALSE)
        goto exit;

    phydata |= BIT_9;

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA400, phydata);
    if (error != FALSE)
        goto exit;

exit:
    return error;
}

boolean Rtl8226b_autoNegoAbility_get(IfxGeth_PhyHandle *const handle, PHY_LINK_ABILITY *pPhyAbility)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 16, &phydata);
    if (error != FALSE)
        goto exit;

    // 10M
    pPhyAbility->Half_10 = (phydata & BIT_5) ? (1) : (0);
    pPhyAbility->Full_10 = (phydata & BIT_6) ? (1) : (0);

    // 100M
    pPhyAbility->Half_100 = (phydata & BIT_7) ? (1) : (0);
    pPhyAbility->Full_100 = (phydata & BIT_8) ? (1) : (0);

    pPhyAbility->FC = (phydata & BIT_10) ? (1) : (0);
    pPhyAbility->AsyFC = (phydata & BIT_11) ? (1) : (0);

    // 1G
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA412, &phydata);
    if (error != FALSE)
        goto exit;

    pPhyAbility->Full_1000 = (phydata & BIT_9) ? (1) : (0);

    // 2.5G
    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 32, &phydata);
    if (error != FALSE)
        goto exit;

    pPhyAbility->adv_2_5G = (phydata & BIT_7) ? (1) : (0);

exit:
    return error;
}

boolean Rtl8226b_autoNegoAbility_set(IfxGeth_PhyHandle *const handle, PHY_LINK_ABILITY *pPhyAbility)
{
    boolean error = TRUE;
    uint16 phydata = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 16, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~(BIT_5 | BIT_6 | BIT_7 | BIT_8 | BIT_10 | BIT_11));

    // 10M
    phydata |= (pPhyAbility->Half_10 ? (BIT_5) : (0));
    phydata |= (pPhyAbility->Full_10 ? (BIT_6) : (0));

    // 100M
    phydata |= (pPhyAbility->Half_100 ? (BIT_7) : (0));
    phydata |= (pPhyAbility->Full_100 ? (BIT_8) : (0));

    phydata |= (pPhyAbility->FC ? (BIT_10) : (0));
    phydata |= (pPhyAbility->AsyFC ? (BIT_11) : (0));

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 16, phydata);
    if (error != FALSE)
        goto exit;

    // 1G
    error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA412, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~BIT_9);

    phydata |= (pPhyAbility->Full_1000 ? (BIT_9) : (0));

    error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA412, phydata);
    if (error != FALSE)
        goto exit;

    // 2.5G
    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 32, &phydata);
    if (error != FALSE)
        goto exit;

    phydata &= (~BIT_7);

    phydata |= (pPhyAbility->adv_2_5G ? (BIT_7) : (0));
    error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 32, phydata);
    if (error != FALSE)
        goto exit;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_AN, 0, &phydata);
    if (error != FALSE)
        goto exit;

    if (phydata & BIT_12)   /* AN_ENABLE */
    {
        phydata |= BIT_9; /* RESTART_AN */
        error = handle->mdioWriteCl45(handle->phyAddr, MMD_AN, 0, phydata);
    }

exit:
    return error;
}

