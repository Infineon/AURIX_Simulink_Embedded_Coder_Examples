boolean Rtl8226b_force_speed_set(IfxGeth_PhyHandle *const handle, uint16 Speed)
{
    boolean error = TRUE;
    uint16 phydata0 = 0, phydata1 = 0;
    boolean support = 0;

    error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0, &phydata0);
    if (error != FALSE)
        goto exit;

    phydata0 &= (~(BIT_6 | BIT_13));

    switch(Speed)
    {
        case 10:
            support = TRUE;
            phydata0 &= (~BIT_6);
            phydata0 &= (~BIT_13);
            break;

        case 100:
            support = TRUE;
            phydata0 &= (~BIT_6);
            phydata0 |= BIT_13;
            break;

        default:
            error = TRUE;
            support = FALSE;
            break;
    }

    if (support)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_VEND2, 0xA5B4, &phydata1);
        if (error != FALSE)
            goto exit;

        phydata1 |= (BIT_15);

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_VEND2, 0xA5B4, phydata1);
        if (error != FALSE)
            goto exit;

        error = handle->mdioWriteCl45(handle->phyAddr, MMD_PMAPMD, 0, phydata0);
        if (error != FALSE)
            goto exit;

        error = Rtl8226b_autoNegoEnable_set(handle, FALSE);
        if (error != FALSE)
            goto exit;
    }
    else
        error = TRUE;

exit:
    return error;
}

boolean Rtl8226b_force_speed_get(IfxGeth_PhyHandle *const handle, uint16 *force_speed)
{
    boolean error = TRUE;
    uint16 phydata = 0;
    boolean AnEnable = 0;

    error = Rtl8226b_autoNegoEnable_get(handle, &AnEnable);
    if (error != FALSE)
        goto exit;

    if (AnEnable==0)
    {
        error = handle->mdioReadCl45(handle->phyAddr, MMD_PMAPMD, 0, &phydata);
        if (error != FALSE)
            goto exit;

        if (((phydata & (BIT_6)) == 0) && ((phydata & (BIT_13)) == 0))
        {
            *force_speed = LINK_SPEED_10M;
        }
        else if (((phydata & (BIT_6)) == 0 ) && ((phydata & (BIT_13)) == BIT_13))
        {
            *force_speed = LINK_SPEED_100M;
        }
        else
        {
            *force_speed = NO_LINK;
        }
    }
    else
        error = TRUE;

exit:
    return error;
}

