#define TIMEOUT_MS                                  (50000)

/* RTL8201FI register addresses */
#define BASIC_MODE_CTRL_REG_ADDR                    (0)
#define BASIC_MODE_STATUS_REG_ADDR                  (1)
#define PHY_ID1_REG_ADDR                            (2)
#define PHY_ID2_REG_ADDR                            (3)

/* RTL8201FI PHY_ID register masks */
#define PHY_ID2_MODEL_NUM_MASK                      (0x03F0)
#define PHY_ID2_MODEL_NUM_OFFSET                    (4)
#define PHY_ID2_REV_NUM_MASK                        (0x0007)
#define PHY_ID2_REV_NUM_OFFSET                      (0)

/* RTL8201FI BASIC_MODE_STATUS register masks */
#define PHY_BASIC_MODE_STATUS_AN_COMPLETE_MASK      (0x0020)
#define PHY_BASIC_MODE_STATUS_AN_COMPLETE_OFFSET    (5)
#define PHY_BASIC_MODE_STATUS_REMOTE_FAULT_MASK     (0x0010)
#define PHY_BASIC_MODE_STATUS_REMOTE_FAULT_OFFSET   (4)
#define PHY_BASIC_MODE_STATUS_AN_ABILITY_MASK       (0x0008)
#define PHY_BASIC_MODE_STATUS_AN_ABILITY_OFFSET     (3)
#define PHY_BASIC_MODE_STATUS_LINK_STATUS_MASK      (0x0004)
#define PHY_BASIC_MODE_STATUS_LINK_STATUS_OFFSET    (2)
#define PHY_BASIC_MODE_STATUS_JABBER_DETECT_MASK    (0x0002)
#define PHY_BASIC_MODE_STATUS_JABBER_DETECT_OFFSET  (1)
#define PHY_BASIC_MODE_STATUS_EXT_CAPABILITY_MASK   (0x0001)
#define PHY_BASIC_MODE_STATUS_EXT_CAPABILITY_OFFSET (0)

/* RTL8201FI BASIC_MODE_CTRL register masks */
#define PHY_BASIC_MODE_CTRL_LOOPBACK_MASK           (0x4000)
#define PHY_BASIC_MODE_CTRL_SPEED_SEL_MASK          (0x2000)
#define PHY_BASIC_MODE_CTRL_AN_EN_MASK              (0x1000)
#define PHY_BASIC_MODE_CTRL_RESTART_AN_MASK         (0x0200)
#define PHY_BASIC_MODE_CTRL_DUPLEX_MODE_MASK        (0x0100)

#define PHY_OUI                                     (0x0732)
#define PHY_ID1                                     (0x001C)
#define PHY_RESET                                   (0x8000)

