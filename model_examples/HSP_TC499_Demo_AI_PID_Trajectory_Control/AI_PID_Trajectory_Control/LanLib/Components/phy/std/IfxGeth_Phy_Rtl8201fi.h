/** \brief Start Auto Negotiation with link partner
 *  \param handle Ethernet PHY handle
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_startAutoNegotiation(IfxGeth_PhyHandle *const handle);

/** \brief Wait for AN to complete
 *  \param handle  Ethernet PHY handle
 *  \param timeout Timeout value
 *  \return TRUE if AN completed successfully, FALSE if error occurred or timeout expired
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_waitAnComplete(IfxGeth_PhyHandle *const handle, uint32 timeout);

/** \brief Get current link state
 *  \param handle    Ethernet PHY handle
 *  \param linkState Current link state
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_getLinkState(IfxGeth_PhyHandle *const handle, IfxGeth_PhyLinkState *linkState);

/** \brief Get current link speed
 *  \param handle    Ethernet PHY handle
 *  \param linkSpeed Current link speed
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_getLinkSpeed(IfxGeth_PhyHandle *const handle, IfxGeth_PhyLinkSpeed *linkSpeed);

/** \brief Get current duplex mode
 *  \param handle     Ethernet PHY handle
 *  \param duplexMode Current duplex mode
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_getDuplexMode(IfxGeth_PhyHandle *const handle, IfxGeth_PhyDuplexMode *duplexMode);

/** \brief Get PHY identifier
 *  \param handle  Ethernet PHY handle
 *  \param phyId   PHY identifier
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_getPhyIdentifier(IfxGeth_PhyHandle *const handle, IfxGeth_PhyIdentifier *phyId);

/** \brief Reset the PHY
 *  \param handle  Ethernet PHY handle
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_reset(IfxGeth_PhyHandle *const handle);

/** \brief Initialize the PHY according to the specified configuration
 *  \param handle     Ethernet PHY handle
 *  \param phyConfig  Ethernet PHY configuration
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean IfxGeth_Eth_Phy_Rtl8201fi_init(IfxGeth_PhyHandle *const handle, IfxGeth_PhyConfig *phyConfig);

