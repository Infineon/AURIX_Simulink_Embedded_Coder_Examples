boolean IfxGeth_Eth_Phy_Rtl8201fi_getPhyIdentifier(IfxGeth_PhyHandle *const handle, IfxGeth_PhyIdentifier *phyId)
{
    boolean error = FALSE;
    uint8 modelNum = 0;
    uint8 revNum = 0;
    uint16 regValue;
    uint32 oui = 0;

    error = (boolean)handle->mdioReadCl22(handle->phyAddr, PHY_ID1_REG_ADDR, &regValue);

    if (error == FALSE)
    {
        oui = regValue << 6;

        error = (boolean)handle->mdioReadCl22(handle->phyAddr, PHY_ID2_REG_ADDR, &regValue);

        if (error == FALSE)
        {
            oui |= (uint32)(regValue >> 10);
            modelNum = (regValue & PHY_ID2_MODEL_NUM_MASK) >> PHY_ID2_MODEL_NUM_OFFSET;
            revNum = (regValue & PHY_ID2_REV_NUM_MASK) >> PHY_ID2_REV_NUM_OFFSET;
        }
    }

    phyId->modelNum = modelNum;
    phyId->revNum = revNum;
    phyId->oui = oui;

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_reset(IfxGeth_PhyHandle *const handle)
{
    boolean error = FALSE;
    uint16 timeoutms = TIMEOUT_MS;
    uint16 regValue;

    /* send phy reset request */
    error = (boolean)handle->mdioWriteCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, PHY_RESET);

    if (error)
    {
        return error;
    }

    do {
        error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, &regValue);

        if (error)
        {
            return error;
        }
    } while (((regValue & PHY_RESET) == PHY_RESET) && (--timeoutms > 0));

    if (timeoutms == 0)
    {
        error = TRUE;
    }

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_startAutoNegotiation(IfxGeth_PhyHandle *const handle)
{
    boolean error = FALSE;
    uint16 regValue;

    error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, &regValue);

    if (error == FALSE)
    {
        regValue |= PHY_BASIC_MODE_CTRL_RESTART_AN_MASK | PHY_BASIC_MODE_CTRL_AN_EN_MASK;
        error = (boolean)handle->mdioWriteCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, regValue);
    }

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_waitAnComplete(IfxGeth_PhyHandle *const handle, uint32 timeout)
{
    boolean error = FALSE;
    boolean anComplete = TRUE;
    uint16 regValue;

    do {
        error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_STATUS_REG_ADDR, &regValue);

        if (error)
        {
            anComplete = FALSE;
        }
    } while (((regValue & PHY_BASIC_MODE_STATUS_AN_COMPLETE_MASK) != PHY_BASIC_MODE_STATUS_AN_COMPLETE_MASK) &&
            (--timeout > 0) &&
            (error != TRUE));

    if (timeout == 0u)
    {
        anComplete = FALSE;
    }

    return anComplete;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_getLinkState(IfxGeth_PhyHandle *const handle, IfxGeth_PhyLinkState *linkState)
{
    boolean error = FALSE;
    uint16 regValue;

    /* Read twice for current link state */
    error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_STATUS_REG_ADDR, &regValue);
    error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_STATUS_REG_ADDR, &regValue);

    if (error)
    {
        *linkState = IfxGeth_PhyLinkState_Down;
        return error;
    }

    if ((regValue & PHY_BASIC_MODE_STATUS_LINK_STATUS_MASK) == PHY_BASIC_MODE_STATUS_LINK_STATUS_MASK)
    {
        *linkState = IfxGeth_PhyLinkState_Up;
    }
    else {
        *linkState = IfxGeth_PhyLinkState_Down;
    }

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_getLinkSpeed(IfxGeth_PhyHandle *const handle, IfxGeth_PhyLinkSpeed *linkSpeed)
{
    boolean error = FALSE;
    uint16 regValue;

    error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, &regValue);

    if (error)
    {
        return error;
    }

    if ((regValue & PHY_BASIC_MODE_CTRL_SPEED_SEL_MASK) == PHY_BASIC_MODE_CTRL_SPEED_SEL_MASK)
    {
        *linkSpeed = IfxGeth_PhyLinkSpeed_100Mbps;
    }
    else {
        *linkSpeed = IfxGeth_PhyLinkSpeed_10Mbps;
    }

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_getDuplexMode(IfxGeth_PhyHandle *const handle, IfxGeth_PhyDuplexMode *duplexMode)
{
    boolean error = FALSE;
    uint16 regValue;

    error = (boolean)handle->mdioReadCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, &regValue);

    if (error)
    {
        return error;
    }

    if ((regValue & PHY_BASIC_MODE_CTRL_DUPLEX_MODE_MASK) == PHY_BASIC_MODE_CTRL_DUPLEX_MODE_MASK)
    {
        *duplexMode = IfxGeth_PhyDuplexMode_Full;
    }
    else {
        *duplexMode = IfxGeth_PhyDuplexMode_Half;
    }

    return error;
}

boolean IfxGeth_Eth_Phy_Rtl8201fi_init(IfxGeth_PhyHandle *const handle, IfxGeth_PhyConfig *phyConfig)
{
    boolean error = FALSE;
    uint16 regValue = 0;
    IfxGeth_PhyIdentifier phyId;

    error = IfxGeth_Eth_Phy_Rtl8201fi_getPhyIdentifier(handle, &phyId);

    if ((error) || (phyId.oui != PHY_OUI))
    {
        return (error = TRUE);
    }

    error = IfxGeth_Eth_Phy_Rtl8201fi_reset(handle);

    if (error == FALSE)
    {
        if (phyConfig->loopback)
        {
            regValue |= PHY_BASIC_MODE_CTRL_LOOPBACK_MASK;
        }

        if (phyConfig->duplexMode == IfxGeth_PhyDuplexMode_Full)
        {
            regValue |= PHY_BASIC_MODE_CTRL_DUPLEX_MODE_MASK;
        }

        if (phyConfig->speed == IfxGeth_PhyLinkSpeed_100Mbps)
        {
            regValue |= PHY_BASIC_MODE_CTRL_SPEED_SEL_MASK;
        }

        error = (uint8)handle->mdioWriteCl22(handle->phyAddr, BASIC_MODE_CTRL_REG_ADDR, regValue);
    }

    return error;
}
