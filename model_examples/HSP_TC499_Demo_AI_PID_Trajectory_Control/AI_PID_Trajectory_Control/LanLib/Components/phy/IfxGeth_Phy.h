/** \brief Link state
 */
typedef enum
{
    IfxGeth_PhyLinkState_Down   = 0,
    IfxGeth_PhyLinkState_Up     = 1
} IfxGeth_PhyLinkState;

/** \brief Link speed
 */
typedef enum
{
    IfxGeth_PhyLinkSpeed_10Mbps     = 0,
    IfxGeth_PhyLinkSpeed_100Mbps    = 1
} IfxGeth_PhyLinkSpeed;

/** \brief Duplex mode
 */
typedef enum
{
    IfxGeth_PhyDuplexMode_Half  = 0,
    IfxGeth_PhyDuplexMode_Full  = 1
} IfxGeth_PhyDuplexMode;

/** \brief PHY Identifier
 */
typedef struct
{
    uint32 oui;
    uint8 modelNum;
    uint8 revNum;
} IfxGeth_PhyIdentifier;

/** \brief PHY configuration structure containing loopback mode, link speed and duplex mode
 */
typedef struct
{
     boolean loopback;
     IfxGeth_PhyLinkSpeed speed;
     IfxGeth_PhyDuplexMode duplexMode;
} IfxGeth_PhyConfig;

/** \brief Handle for Ethernet PHY management containing PHY address and functions for Clause22/45 register access
 */
typedef struct
{
     uint8 phyAddr;
     uint8 (*mdioWriteCl22)(uint8 phyAddr, uint16 regAddr, uint16 regVal);
     uint8 (*mdioReadCl22)(uint8 phyAddr, uint16 regAddr, uint16 *const regVal);
     uint8 (*mdioWriteCl45)(uint8 phyAddr, uint8 devAddr, uint16 regAddr, uint16 regVal);
     uint8 (*mdioReadCl45)(uint8 phyAddr, uint8 devAddr, uint16 regAddr, uint16 *const regVal);
     IfxPort_Pin* phy_reset_pin;
} IfxGeth_PhyHandle;


