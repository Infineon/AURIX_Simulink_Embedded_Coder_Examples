/** \brief Initializes HSPY and GETH for SMI and RMII 100Mbps communication
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean Board_setupEthernetCtrl(void);

/** \brief Initializes the specified Ethernet PHY for 100Mbps full-duplex communication
 *  \param phyHandle Ethernet PHY handle
 *  \return FALSE if no error occurred, TRUE otherwise
 */
boolean Board_initEthernetPhy(IfxGeth_PhyHandle *phyHandle);

/** \brief Write Ethernet PHY register via MDIO Clause22 for MAC0
 *  \param phyAddr Ethernet PHY address
 *  \param regAddr Register address to be written
 *  \param regVal  Register value to be written
 *  \return zero if no error occurred, non-zero otherwise
 */
uint8 writeCl22Mac0(uint8 phyAddr, uint16 regAddr, uint16 regVal);

/** \brief Read Ethernet PHY register via MDIO Clause22 for MAC0
 *  \param phyAddr Ethernet PHY address
 *  \param regAddr Register address to be read
 *  \param regVal  Value of the read register
 *  \return zero if no error occurred, non-zero otherwise
 */
uint8 readCl22Mac0(uint8 phyAddr, uint16 regAddr, uint16 *const regVal);

/** \brief Write Ethernet PHY register via MDIO Clause45 for MAC0
 *  \param phyAddr Ethernet PHY address
 *  \param devAddr Device address/MMD
 *  \param regAddr Register address to be written
 *  \param regVal  Register value to be written
 *  \return zero if no error occurred, non-zero otherwise
 */
uint8 writeCl45Mac0(uint8 phyAddr, uint8 devAddr, uint16 regAddr, uint16 regVal);

/** \brief read Ethernet PHY register via MDIO Clause45 for MAC0
 *  \param phyAddr Ethernet PHY address
 *  \param devAddr Device address/MMD
 *  \param regAddr Register address to be read
 *  \param regVal  Value of the read register
 *  \return zero if no error occurred, non-zero otherwise
 */
uint8 readCl45Mac0(uint8 phyAddr, uint8 devAddr, uint16 regAddr, uint16 *const regVal);

