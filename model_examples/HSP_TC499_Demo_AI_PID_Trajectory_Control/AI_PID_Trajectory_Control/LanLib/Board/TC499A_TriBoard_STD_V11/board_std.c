static boolean Board_setupHsphy(void)
{
    boolean error = FALSE;

    error = IfxHsphy_enableModule(&MODULE_HSPHY);

    if (error == FALSE)
    {
        error = (uint8)IfxHsphy_resetModule(&MODULE_HSPHY);
    }

    if (error == FALSE)
    {
        /* Select RMII external PHY port interface */
        MODULE_HSPHY.CTRL.ETH.B.EPR = 0x2;

        /* Setup RMII pins */
        const IfxHsphy_Geth_RmiiPins rmiiPins = {
            .crsDiv = &IfxGeth0_CRSDVA_P11_11_IN,
            .refClk = &IfxGeth0_REFCLKA_P11_12_IN,
            .rxd0 = &IfxGeth0_RXD0A_P11_10_IN,
            .rxd1 = &IfxGeth0_RXD1A_P11_9_IN,
            .txd0 = &IfxGeth0_TXD_MII_P11_3_OUT,
            .mdc = &IfxGeth0_MDC0_P12_0_OUT,
            .txd1 = &IfxGeth0_TXD_MII_P11_2_OUT,
            .txEn = &IfxGeth0_TXEN_RMII_P11_6_OUT,
            .mdio0 = &IfxGeth0_MDIO_P12_1_INOUT,
            .mdio1 = &IfxGeth0_MDIO_P12_1_INOUT
        };

        IfxHsphy_Geth_RmiiCfg rmiiConfig = {
                .rmiiPins = &rmiiPins
        };

        IfxHsphy_Geth_setRmiiPins(&MODULE_HSPHY, &rmiiConfig);

        /* Setup MDIO pins */
        const IfxHsphy_Geth_MdioPins mdioPins = {
            .mdc = &IfxGeth0_MDC0_P12_0_OUT,          /* MDC */
            .mdio = &IfxGeth0_MDIO_P12_1_INOUT,       /* MDIO */
            .portIndex = IfxHsphy_Mdio_PortIndex_0    /* port index is always 0 */
        };

        IfxHsphy_Geth_setMdioOnlyPins(&MODULE_HSPHY, &mdioPins);
    }

    return error;
}

static void Board_setupGeth(void)
{
    IfxGeth_Eth_Config gethConfig;

    /* get the default configuration for the GETH module */
    IfxGeth_Eth_initModuleConfig(&gethConfig, &MODULE_GETH0);

    /* set RMII as interface to the HSPHY */
    gethConfig.port[IfxGeth_PortIndex_0].phyInterfaceMode = IfxGeth_PhyInterfaceMode_rmii_100;

    /* configure Ethernet Bridge */
    /* configure the bridge to operate in single port mode, MAC0 only is used */
    gethConfig.bridge.mode = IfxGeth_BridgePortMode_singlePort0;
    /* enable TxQueue0 on bridge port 0 */
    gethConfig.bridge.portConfig[IfxGeth_PortIndex_0].configTxQueuesAndRxChannels.enable.txQueue0 = 1;
    /* enable RxChannel0 on bridge port 0 */
    gethConfig.bridge.portConfig[IfxGeth_PortIndex_0].configTxQueuesAndRxChannels.enable.rxChannel0 = 1;

    /* configure Ethernet DMA */
    /* set transmit buffer size in the Tx.Dscr */
    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].txBuffer1Size = GETH_DMA_CH0_TX_BUFFER_SIZE;
    /* assign the transmit buffer */
    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].txBuffer1StartAddress = (uint32*)g_gethDmaCh0TxBuffer_u8;
    /* set receive buffer size in the Rx.Dscr */
    gethConfig.dma.rxChannel[IfxGeth_DmaChannel_0].rxBuffer1Size = GETH_DMA_CH0_RX_BUFFER_SIZE;
    /* assign the receive buffer */
    gethConfig.dma.rxChannel[IfxGeth_DmaChannel_0].rxBuffer1StartAddress = (uint32*)g_gethDmaCh0RxBuffer_u8;

    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].sourceAddressControl = IfxGeth_SourceAddressControl_replaceWithMacAddress0;

    /* prepare the DMA Tx/Rx interrupt configuration */
    /* set up the DMA Tx priority */
    /* set up the DMA Tx interrupt receiver, CPU0 */
    gethConfig.dma.txInterrupt[IfxGeth_DmaChannel_0].provider = IfxSrc_Tos_cpu0;
    /* set up virtual machine id */
    gethConfig.dma.txInterrupt[IfxGeth_DmaChannel_0].vmId = IfxSrc_VmId_none;

    /* set up the DMA Rx priority */
    /* set up the DMA Rx interrupt receiver, CPU0 */
    gethConfig.dma.rxInterrupt[IfxGeth_DmaChannel_0].provider = IfxSrc_Tos_cpu0;
    /* set up virtual machine id */
    gethConfig.dma.rxInterrupt[IfxGeth_DmaChannel_0].vmId = IfxSrc_VmId_none;

    gethConfig.bypassKernelReset = TRUE;
    /* configure the "own" MAC address into slot0 */
    memcpy(gethConfig.port[IfxGeth_PortIndex_0].mac.macAddress, g_netifHwAddr, 6);

    /* perform the GETH configuration */
    IfxGeth_Eth_initModule(&geth, &gethConfig);

    setupGethMdioAccess(&geth, BOARD_ETH_PHY_CLAUSE22);
}

boolean Board_setupEthernetCtrl(void)
{
    boolean error = FALSE;

    {
        MODULE_PMS.VMONP.VDDHSIFCON.U = 0x1A3A4A31;
        MODULE_PMS.VMONP.VDDPHY0CON.U = 0x1EF84D97;
        MODULE_PMS.VMONP.VDDPHY1CON.U = 0x1EF84D97;
        MODULE_PMS.VMONP.VDDPHPHY0CON.U = 0x15944A31;
        MODULE_PMS.VMONP.VDDPHPHY1CON.U = 0x15944A31;

        MODULE_PMS.VMONP.VDDHSIFRST.U = 0x2F868000;
        MODULE_PMS.VMONP.VDDPHY0RST.U = 0x2F8F0000;
        MODULE_PMS.VMONP.VDDPHY1RST.U = 0x2F8F0000;
        MODULE_PMS.VMONP.VDDPHPHY0RST.U = 0x2D850000;
        MODULE_PMS.VMONP.VDDPHPHY1RST.U = 0x2D850000;
    }

    error = Board_setupHsphy();

    if (error == FALSE)
    {
        Board_setupGeth();
    }

    return error;
}

boolean Board_initEthernetPhy(IfxGeth_PhyHandle *phyHandle)
{
    boolean error = FALSE;

    IfxGeth_PhyConfig phyConfig = {
            .loopback = FALSE,
            .duplexMode = IfxGeth_PhyDuplexMode_Full,
            .speed = IfxGeth_PhyLinkSpeed_100Mbps
    };

    error = IfxGeth_Eth_Phy_Rtl8201fi_init(phyHandle,&phyConfig);

    return error;
}

