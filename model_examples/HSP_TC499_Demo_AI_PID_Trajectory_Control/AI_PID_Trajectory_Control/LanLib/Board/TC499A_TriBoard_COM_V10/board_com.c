IfxGeth_Eth geth = {.gethSFR=&MODULE_GETH0};

void our_IfxGeth_resetModule(Ifx_GETH *gethSFR)
{
#if (IFX_PROT_ENABLED == 1U)
    IfxApProt_setState((Ifx_PROT_PROT *)&(gethSFR->PROTE), IfxApProt_State_config);
#endif
    
    *(uint32*)(0xF9000000u + 0xC) |= 1u;
    *(uint32*)(0xF9000000u + 0x10) |= 1u;
    /* gethSFR->RST.CTRLA.U = 1;          /1* Only if both Kernel reset bits are set a reset is executed *1/ */
    /* gethSFR->RST.CTRLB.U = 1; */

    while ((gethSFR->RST.STAT.U & 0x1) == 0)   /* Wait until reset is executed */
    {}

    *(uint32*)(0xF9000000u + 0x10) |= 0x80000000;
    /* gethSFR->RST.CTRLB.U = 1;       /1* Clear Kernel reset status bit *1/ */

    while (gethSFR->RST.STAT.U == 1)   /* Wait until KRST is cleared, only after this reset sequence is completed */
    {}

#if (IFX_PROT_ENABLED == 1U)
    IfxApProt_setState((Ifx_PROT_PROT *)&(gethSFR->PROTE), IfxApProt_State_run);
#endif
}

boolean Board_Geth_Init_Phase1(void)
{
    MODULE_PMS.VMONP.VDDHSIFCON.U = 0x1A3A4A31;
    MODULE_PMS.VMONP.VDDPHY0CON.U = 0x1EF84D97;
    MODULE_PMS.VMONP.VDDPHY1CON.U = 0x1EF84D97;
    MODULE_PMS.VMONP.VDDPHPHY0CON.U = 0x15944A31;
    MODULE_PMS.VMONP.VDDPHPHY1CON.U = 0x15944A31;

    MODULE_PMS.VMONP.VDDHSIFRST.U = 0x2F868000;
    MODULE_PMS.VMONP.VDDPHY0RST.U = 0x2F8F0000;
    MODULE_PMS.VMONP.VDDPHY1RST.U = 0x2F8F0000;
    MODULE_PMS.VMONP.VDDPHPHY0RST.U = 0x2D850000;
    MODULE_PMS.VMONP.VDDPHPHY1RST.U = 0x2D850000;


    /*********************************************************************************************************************************************/
    /* enable GETH0 module                                                                                                                       */
    /*********************************************************************************************************************************************/
    if (IfxGeth_isModuleEnabled(&MODULE_GETH0) == FALSE)
    {
        IfxGeth_enableModule(&MODULE_GETH0);

        our_IfxGeth_resetModule(&MODULE_GETH0);
    }

    /*********************************************************************************************************************************************/
    /* enable HSPHY module                                                                                                                       */
    /*********************************************************************************************************************************************/
    if (IfxHsphy_isModuleEnabled(&MODULE_HSPHY) == FALSE)
    {
        IfxHsphy_enableModule(&MODULE_HSPHY);

        IfxHsphy_resetModule(&MODULE_HSPHY);

        Board_Hsphy_Mp8G_SetMuxToEth();
    }

    geth.gethSFR->MACEN.U = 1;

    /*********************************************************************************************************************************************/
    /* deassert Phy resets                                                                                                                       */
    /*********************************************************************************************************************************************/

    if (Board_Eth_deassertPhyReset(&PHY_HANDLE) == TRUE)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* set up MDIO interface                                                                                                                     */
    /*********************************************************************************************************************************************/
    Board_Eth_initMdio0Pins();

    return FALSE;
}

boolean Board_Geth_Init_Phase2(void)
{
    IfxGeth_Eth_Config gethConfig;
    IfxGeth_Eth_initModuleConfig(&gethConfig, &MODULE_GETH0);

    memcpy(gethConfig.port[IfxGeth_PortIndex_0].mac.macAddress, g_netifHwAddr, 6);
    gethConfig.bridge.mode = IfxGeth_BridgePortMode_singlePort0;
    /* enable TxQueue0 on bridge port 0 */
    gethConfig.bridge.portConfig[IfxGeth_PortIndex_0].configTxQueuesAndRxChannels.enable.txQueue0 = 1;
    /* enable RxChannel0 on bridge port 0 */
    gethConfig.bridge.portConfig[IfxGeth_PortIndex_0].configTxQueuesAndRxChannels.enable.rxChannel0 = 1;

    /* configure Ethernet DMA */
    /* set transmit buffer size in the Tx.Dscr */
    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].txBuffer1Size = GETH_DMA_CH0_TX_BUFFER_SIZE;
    /* assign the transmit buffer */
    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].txBuffer1StartAddress = (uint32*)txBufferCh0;
    /* set receive buffer size in the Rx.Dscr */
    gethConfig.dma.rxChannel[IfxGeth_DmaChannel_0].rxBuffer1Size = GETH_DMA_CH0_RX_BUFFER_SIZE;
    /* assign the receive buffer */
    gethConfig.dma.rxChannel[IfxGeth_DmaChannel_0].rxBuffer1StartAddress = (uint32*)rxBufferCh0;

    gethConfig.dma.txChannel[IfxGeth_DmaChannel_0].sourceAddressControl = IfxGeth_SourceAddressControl_replaceWithMacAddress0;

    /* prepare the DMA Tx/Rx interrupt configuration */
    /* set up the DMA Tx priority */
    /* set up the DMA Tx interrupt receiver, CPU0 */
    gethConfig.dma.txInterrupt[IfxGeth_DmaChannel_0].provider = IfxSrc_Tos_cpu0;
    /* set up virtual machine id */
    gethConfig.dma.txInterrupt[IfxGeth_DmaChannel_0].vmId = IfxSrc_VmId_none;

    /* set up the DMA Rx priority */
    /* set up the DMA Rx interrupt receiver, CPU0 */
    gethConfig.dma.rxInterrupt[IfxGeth_DmaChannel_0].provider = IfxSrc_Tos_cpu0;
    /* set up virtual machine id */
    gethConfig.dma.rxInterrupt[IfxGeth_DmaChannel_0].vmId = IfxSrc_VmId_none;
    
    // NOTE: Not true as we have smii 1000 but does not matter for the configuration
    gethConfig.port[IfxGeth_PortIndex_0].phyInterfaceMode = IfxGeth_PhyInterfaceMode_gmii_1000;

    gethConfig.bypassKernelReset = TRUE;

    IfxGeth_Eth_initModule(&geth, &gethConfig);
    return FALSE;
}

boolean Board_RealtekPhy_Init(IfxGeth_PhyHandle *const phyInstance_p)
{
    sint32 result_s32;
    PHY_LINK_ABILITY linkAbility_t;
    linkAbility_t.Full_1000 = 1;
    linkAbility_t.adv_2_5G = 1;

    result_s32 = TRUE;

    if (phyInstance_p == NULL)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: init Phy                                                                                                                         */
    /*********************************************************************************************************************************************/
    if (Rtl8226b_phy_init(phyInstance_p, &linkAbility_t, TRUE) != FALSE)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: check Phy patch state                                                                                                            */
    /*********************************************************************************************************************************************/
    if (Rtl8226b_check_patch(phyInstance_p) != FALSE)
    {
        return TRUE;
    }

    return FALSE;
}

boolean Board_RealtekPhy_Setup(IfxGeth_PhyHandle *const phyInstance_p)
{
    boolean result;
    uint16 speed_u16;
    uint32 timeout_u32;
    boolean serdesLinkActive_b;
    PHY_SERDES_MODE serdesMode_t;
    IfxGeth_PhyLinkState linkActive_b;
    PHY_LINK_ABILITY linkAbility_t;
    linkAbility_t.Full_1000 = 1;
    linkAbility_t.adv_2_5G = 1;

    result = TRUE;

    if (phyInstance_p == NULL)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: check ethernet link state                                                                                                        */
    /*********************************************************************************************************************************************/
    timeout_u32 = 0xFFFF;
    do
    {
        result = Rtl8226b_is_link(phyInstance_p, &linkActive_b);
        timeout_u32--;
    }
    while ((result == FALSE) && (linkActive_b == IfxGeth_PhyLinkState_Down) && (timeout_u32 > 0));

    if ((timeout_u32 == 0) || (result != FALSE))
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: get ethernet link speed                                                                                                          */
    /*********************************************************************************************************************************************/
    if (Rtl8226b_speed_get(phyInstance_p, &speed_u16) != FALSE)
    {
        return TRUE;
    }

    if (linkActive_b != TRUE)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* HSPHY: init HSPHY depending on ethernet link speed                                                                                        */
    /*********************************************************************************************************************************************/
    if (speed_u16 == LINK_SPEED_2P5G)
    {
        if (Board_HsphyModeInit(&MODULE_HSPHY, 0, IfxHsphy_TrgtDeviceSpeed_2P5G) != FALSE)
        {
            return TRUE;
        }
    }
    else
    {
        if (Board_HsphyModeInit(&MODULE_HSPHY, 0, IfxHsphy_TrgtDeviceSpeed_1G) != FALSE)
        {
            return TRUE;
        }
    }

    /*********************************************************************************************************************************************/
    /* Realtek: set SerDes link options                                                                                                          */
    /*********************************************************************************************************************************************/
    if (Rtl8226b_serdes_option_set(phyInstance_p, PHY_SERDES_OPTION_2500BASEX_SGMII) != FALSE)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: disable auto negotiation for SerDes link                                                                                         */
    /*********************************************************************************************************************************************/
    if (Rtl8226b_serdes_autoNego_set(phyInstance_p, FALSE) != FALSE)
    {
        return TRUE;
    }

    /*********************************************************************************************************************************************/
    /* Realtek: check for SerDes link to the HSPHY                                                                                               */
    /*********************************************************************************************************************************************/
    timeout_u32 = 0xFFFF;
    do
    {
        result = Rtl8226b_serdes_link_get(phyInstance_p, &serdesLinkActive_b, &serdesMode_t);
        timeout_u32--;
    }
    while ((result == FALSE) && (serdesLinkActive_b == FALSE) && (timeout_u32 > 0));

    if ((timeout_u32 == 0) || (result != FALSE))
    {
        return TRUE;
    }

    if (serdesLinkActive_b != TRUE)
    {
        return TRUE;
    }

    return FALSE;
}


