boolean Board_HsphyModeInit(Ifx_HSPHY *const hsphyInstance_p, const uint8 phyIdx_u8, IfxHsphy_TrgtDeviceSpeed devSpeed)
{

    if ((hsphyInstance_p == NULL) || (phyIdx_u8 >= HSPHY_NUMBER_OF_PORTS))
    {
        return TRUE;
    }

    if (g_hsphyInitDone_b[phyIdx_u8] == TRUE)
    {
        return FALSE;
    }

    hsphyInstance_p->CTRL.ETH.B.EPR = 4; /* USXGMII / SerialGMII Internal PHY (data clocks generated on Chip) is selected */
    while(!IfxHsphy_isPhyReady(hsphyInstance_p, phyIdx_u8));
    IfxHsphy_setExtLdDone(hsphyInstance_p, phyIdx_u8);
    IfxHsphy_GethXpcsParams conf = {.xpcsIndex=phyIdx_u8, .xpcsRefClk=IfxHsphy_XpcsRefClk_25Mhz};
    /* our_IfxHsphy_resetXpcs(hsphyInstance_p, &conf); */
    myIfxHsphy_resetXpcs(hsphyInstance_p, &conf);
    myIfxHsphy_Geth_setSgmiiSpeedMode(hsphyInstance_p, devSpeed, &conf);
    g_hsphyInitDone_b[phyIdx_u8] = TRUE;

    return FALSE;
}
